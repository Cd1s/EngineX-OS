#include "textflag.h"

// func fma4RowAVX2(n int, a0, a1, a2, a3 float32, b, c0, c1, c2, c3 *float32)
TEXT ·fma4RowAVX2(SB), NOSPLIT, $0-64
	MOVQ n+0(FP), CX
	VBROADCASTSS a0+8(FP), Y0
	VBROADCASTSS a1+12(FP), Y1
	VBROADCASTSS a2+16(FP), Y2
	VBROADCASTSS a3+20(FP), Y3
	MOVQ b+24(FP), SI
	MOVQ c0+32(FP), DI
	MOVQ c1+40(FP), R8
	MOVQ c2+48(FP), R9
	MOVQ c3+56(FP), R10
	XORQ AX, AX

loop8:
	MOVQ CX, DX
	SUBQ AX, DX
	CMPQ DX, $8
	JL tail
	VMOVUPS (SI)(AX*4), Y4
	VMOVUPS (DI)(AX*4), Y5
	VMOVUPS (R8)(AX*4), Y6
	VMOVUPS (R9)(AX*4), Y7
	VMOVUPS (R10)(AX*4), Y8
	VFMADD231PS Y0, Y4, Y5
	VFMADD231PS Y1, Y4, Y6
	VFMADD231PS Y2, Y4, Y7
	VFMADD231PS Y3, Y4, Y8
	VMOVUPS Y5, (DI)(AX*4)
	VMOVUPS Y6, (R8)(AX*4)
	VMOVUPS Y7, (R9)(AX*4)
	VMOVUPS Y8, (R10)(AX*4)
	ADDQ $8, AX
	JMP loop8

tail:
	CMPQ AX, CX
	JGE done
	VMOVSS (SI)(AX*4), X4
	VMOVSS (DI)(AX*4), X5
	VMOVSS (R8)(AX*4), X6
	VMOVSS (R9)(AX*4), X7
	VMOVSS (R10)(AX*4), X8
	VFMADD231SS X0, X4, X5
	VFMADD231SS X1, X4, X6
	VFMADD231SS X2, X4, X7
	VFMADD231SS X3, X4, X8
	VMOVSS X5, (DI)(AX*4)
	VMOVSS X6, (R8)(AX*4)
	VMOVSS X7, (R9)(AX*4)
	VMOVSS X8, (R10)(AX*4)
	INCQ AX
	JMP tail

done:
	VZEROUPPER
	RET
